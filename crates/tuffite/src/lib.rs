//! Public Rust API for applications built with Tuffite.
//!
//! Applications declare a main with explicit Application, Browser and Utility types.
//! Application and profile state are created only in the browser process. The main factory assembles
//! embedding definitions in each process; `Application::setup` prepares each native process role.
//!
//! ```no_run
//! # mod example {
//! use tuffite::{Application, ApplicationContext, Result, Browser, BrowserContext};
//! struct App;
//! impl Application for App {
//!     fn new(_: ApplicationContext) -> Result<Self> { Ok(Self) }
//! }
//! struct Profile;
//! impl Browser for Profile {
//!     fn new(_: BrowserContext) -> Result<Self> { Ok(Self) }
//! }
//! #[tuffite::main]
//! fn main() -> tuffite::Embedding<App> {
//!     tuffite::Embedding::new().browser::<Profile>()
//! }
//! # }
//! ```

