/// Builds a statically checked command registry from explicitly annotated
/// handlers. Each handler must use `#[tuffite::command(endpoint::Type)]`.
#[macro_export]
macro_rules! generate_handler {
    () => {
        compile_error!("tuffite::generate_handler! requires at least one command handler")
    };
    ($first:path $(, $handler:path)* $(,)?) => {{
        type __TuffiteBrowser =
            <$first as $crate::__private::CommandHandler>::Target;

        fn __tuffite_dispatch(
            browser: &mut __TuffiteBrowser,
            command: $crate::Command<'_>,
        ) -> $crate::CommandResult {
            if command.id()
                == <$first as $crate::__private::CommandHandler>::COMMAND.id()
            {
                return <$first as $crate::__private::CommandHandler>::dispatch(
                    browser,
                    command,
                );
            }
            $(
                if command.id()
                    == <$handler as $crate::__private::CommandHandler>::COMMAND.id()
                {
                    return <$handler as $crate::__private::CommandHandler>::dispatch(
                        browser,
                        command,
                    );
                }
            )*
            Err($crate::CommandError::UnknownCommand)
        }

        $crate::__private::CommandRegistry::<__TuffiteBrowser>::new(
            __tuffite_dispatch,
            &[
                <$first as $crate::__private::CommandHandler>::COMMAND,
                $(<$handler as $crate::__private::CommandHandler>::COMMAND,)*
            ],
        )
    }};
}

