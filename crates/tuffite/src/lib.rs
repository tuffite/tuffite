//! Public Rust API for applications built with Tuffite.
//!
//! Applications declare a logical main with explicit Browser and Utility types.
//! Browser state is created only in the main process. The main factory assembles
//! definitions in each process, while `before_startup` runs for each native process role.
//!
//! ```no_run
//! # mod example {
//! use tuffite::{Browser, BrowserContext, ApplicationResult};
//! struct MyBrowser;
//! #[tuffite::browser]
//! impl Browser for MyBrowser {
//!     fn new(_: BrowserContext) -> ApplicationResult<Self> { Ok(Self) }
//! }
//! #[tuffite::main(browser = MyBrowser)]
//! fn main() -> tuffite::app::Builder<MyBrowser> {
//!     tuffite::app::Builder::new()
//!         .before_startup(|launch| {
//!             launch.argv_mut().retain(|arg| arg != "--business-debug");
//!             Ok(())
//!         })
//! }
//! # }
//! ```

