//! Off-UI-thread dispatch scheduling for the Rust side of the C ABI.
//!
//! Chromium's UI sequence must never block on an application command handler.
//! Historically `dispatch_browser` locked the global runtime table and
//! then invoked the user handler inline, which pinned the UI thread for the
//! duration of every command. This module moves handler execution onto a
//! dedicated worker thread per Runtime while keeping the ABI contract simple:
//!
//! - `dispatch_browser` returns as soon as the request is enqueued.
//! - The worker decodes the request, runs the handler, encodes the response
//!   preserving the wire `request_id`, and posts it via
//!   `RuntimeEventKind::CommandResponse`.
//! - Framework correlates responses to invocations by reading the `request_id`
//!   embedded in the response header.
//! - Bounded queue depth applies backpressure via `ResourceExhausted`.
//! - Per-request soft deadlines shed load if a request has spent too long in
//!   the queue by the time the worker reaches it.
//!
//! This module intentionally does not depend on Tokio. The scheduler is a
//! single bounded MPSC channel drained by one supervised worker thread. A
//! future revision can grow this into a bounded pool once
//! [`Browser::dispatch`] is refactored to be concurrency-safe.

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::mpsc;
use std::time::{Duration, Instant};

use tuffite_abi::{RuntimeEventKind, Status};

use crate::abi::NativeHost;
use crate::browser::{Browser, Command};
use crate::protocol;

/// Default number of requests permitted to sit in the dispatch queue between
/// the FFI enqueue point and the worker. Chosen conservatively so a runaway
/// renderer cannot pile unbounded pending state into the browser process, but
/// large enough that batched startup traffic (framework generation, window
/// setup) does not immediately backpressure.
pub const DEFAULT_MAX_QUEUE_DEPTH: usize = 256;

/// Default soft deadline applied to a request between enqueue and worker
/// pickup. If the worker reaches a task older than this, it reports
/// `HandlerFailed` with a "timeout" message instead of running the handler.
/// This gives us a defensive shed-load knob without needing runtime
/// timers per request.
pub const DEFAULT_QUEUE_DEADLINE: Duration = Duration::from_secs(30);

/// Sentinel used inside the wire header to mark responses generated by the
/// scheduler itself (e.g. queue timeout, cancelled shutdown). Applications
/// never observe this value because they never see the wire.
const SCHEDULER_TIMEOUT_MSG: &str = "queue deadline exceeded";
const SCHEDULER_CANCELLED_MSG: &str = "runtime stopped before dispatch";

/// One queued dispatch. The event bytes are owned so the worker does not
/// depend on the enqueuer's lifetime, which lets the FFI return immediately.
struct DispatchTask {
    request_id: u64,
    enqueued_at: Instant,
    event: Vec<u8>,
}

/// Sender side of the dispatch queue. Cheap to clone but only the ABI
/// entrypoint holds one.
#[derive(Clone)]
pub(crate) struct DispatchSender {
    tx: mpsc::SyncSender<DispatchTask>,
    in_flight: Arc<AtomicU64>,
    max_queue_depth: u64,
}

impl DispatchSender {
    /// Attempts to enqueue a dispatch. Returns
    /// - `Ok(())` when the request is enqueued and the worker will process it.
    /// - `Err(Status::ResourceExhausted)` when the bounded queue is full.
    /// - `Err(Status::InvalidState)` when the worker has already shut
    ///   down, which happens after the Runtime enters `Stopping`.
    pub(crate) fn enqueue(&self, request_id: u64, event: Vec<u8>) -> Result<(), Status> {
        self.in_flight
            .fetch_update(Ordering::AcqRel, Ordering::Acquire, |count| {
                (count < self.max_queue_depth).then_some(count + 1)
            })
            .map_err(|_| Status::ResourceExhausted)?;
        let task = DispatchTask {
            request_id,
            enqueued_at: Instant::now(),
            event,
        };
        if let Err(error) = self.tx.try_send(task) {
            // Roll back the reservation. Either the worker is gone
            // (`InvalidState`) or the channel is momentarily full and we
            // want the caller to retry after applying backpressure.
            self.in_flight.fetch_sub(1, Ordering::AcqRel);
            return Err(match error {
                mpsc::TrySendError::Full(_) => Status::ResourceExhausted,
                mpsc::TrySendError::Disconnected(_) => Status::InvalidState,
            });
        }
        Ok(())
    }
}

/// Scheduler owning the worker thread. Dropping shuts the worker down.
pub(crate) struct DispatchScheduler {
    // `Option` so `shutdown()` can move the sender out, dropping it before
    // joining. Once removed, `enqueue` returns InvalidState.
    sender: Option<DispatchSender>,
    // Held only so the worker thread can be joined explicitly on shutdown.
    worker: Option<std::thread::JoinHandle<Box<dyn Browser>>>,
    stopping: Arc<AtomicBool>,
}

impl DispatchScheduler {
    pub(crate) fn start(
        runtime_identity: &Arc<AtomicU64>,
        application: Box<dyn Browser>,
        callbacks: NativeHost,
    ) -> Self {
        Self::start_with_bounds(
            runtime_identity,
            application,
            callbacks,
            DEFAULT_MAX_QUEUE_DEPTH,
            DEFAULT_QUEUE_DEADLINE,
        )
    }

    pub(crate) fn start_with_bounds(
        runtime_identity: &Arc<AtomicU64>,
        application: Box<dyn Browser>,
        callbacks: NativeHost,
        max_queue_depth: usize,
        queue_deadline: Duration,
    ) -> Self {
        let (tx, rx) = mpsc::sync_channel::<DispatchTask>(max_queue_depth);
        let in_flight = Arc::new(AtomicU64::new(0));
        let worker_in_flight = Arc::clone(&in_flight);
        let worker_identity = Arc::clone(runtime_identity);
        let stopping = Arc::new(AtomicBool::new(false));
        let worker_stopping = Arc::clone(&stopping);
        let name = "tuffite-dispatch";
        let worker = std::thread::Builder::new()
            .name(name.to_owned())
            .spawn(move || {
                run_worker(
                    &worker_identity,
                    rx,
                    application,
                    callbacks,
                    &worker_in_flight,
                    queue_deadline,
                    &worker_stopping,
                )
            })
            .expect("tuffite dispatch worker thread spawn");
        Self {
            sender: Some(DispatchSender {
                tx,
                in_flight,
                max_queue_depth: u64::try_from(max_queue_depth).unwrap_or(u64::MAX),
            }),
            worker: Some(worker),
            stopping,
        }
    }

    /// Enqueues one dispatch onto the worker. Returns the same status codes
    /// as [`DispatchSender::enqueue`] and additionally
    /// [`Status::InvalidState`] once [`shutdown`] has been called.
    pub(crate) fn enqueue(&self, request_id: u64, event: Vec<u8>) -> Result<(), Status> {
        let Some(sender) = self.sender.as_ref() else {
            return Err(Status::InvalidState);
        };
        sender.enqueue(request_id, event)
    }

    /// Signals shutdown by dropping the sender clone in the scheduler and
    /// waits for the worker to drain any in-flight items. Any items still in
    /// the queue are surfaced to Framework as scheduler-cancelled responses so
    /// pending browser-side callbacks can complete instead of leaking.
    pub(crate) fn shutdown(&mut self) -> Option<Box<dyn Browser>> {
        // Admission/removal is serialized by the runtime handle table. Once
        // removed, this scheduler has one owner; no sender/worker lock is needed.
        self.stopping.store(true, Ordering::Release);
        self.sender.take();
        self.worker.take().and_then(|worker| {
            if let Ok(application) = worker.join() {
                Some(application)
            } else {
                tracing::error!("dispatch worker panicked");
                None
            }
        })
    }
}

// The worker takes ownership of `rx` so the receiver lives on the worker
// thread and is dropped when the loop exits. Clippy sees `&self`-taking
// methods and cannot prove consumption, so we opt out of the lint here.
#[allow(clippy::needless_pass_by_value)]
fn run_worker(
    runtime_identity: &Arc<AtomicU64>,
    rx: mpsc::Receiver<DispatchTask>,
    mut application: Box<dyn Browser>,
    callbacks: NativeHost,
    in_flight: &Arc<AtomicU64>,
    queue_deadline: Duration,
    stopping: &AtomicBool,
) -> Box<dyn Browser> {
    while let Ok(task) = rx.recv() {
        let _span =
            tracing::debug_span!("runtime.dispatch", request_id = task.request_id).entered();
        let sit_time = task.enqueued_at.elapsed();
        let response = if stopping.load(Ordering::Acquire) {
            protocol::encode_scheduler_failure(task.request_id, SCHEDULER_CANCELLED_MSG)
        } else if sit_time > queue_deadline {
            // Bounce the request without executing the handler. The
            // handler sees the FFI as always making progress, and the
            // browser-side callback receives a well-formed error response
            // instead of hanging.
            tracing::warn!("dispatch queue deadline exceeded");
            protocol::encode_scheduler_failure(task.request_id, SCHEDULER_TIMEOUT_MSG)
        } else {
            protocol::dispatch_with(&task.event, |id, schema_fingerprint, payload| {
                application.dispatch(Command::new(id, schema_fingerprint, payload))
            })
        };
        let runtime_handle = runtime_identity.load(Ordering::Acquire);
        if runtime_handle != 0 {
            let _ = post_response(runtime_handle, callbacks, &response);
        }
        in_flight.fetch_sub(1, Ordering::AcqRel);
    }
    application
}

fn post_response(runtime_handle: u64, callbacks: NativeHost, response: &[u8]) -> Status {
    callbacks.post_event(runtime_handle, RuntimeEventKind::CommandResponse, response)
}

impl Drop for DispatchScheduler {
    fn drop(&mut self) {
        let _ = self.shutdown();
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Mutex;
    use tuffite_abi::ByteSlice;

    #[test]
    fn concurrent_senders_reserve_capacity_without_spurious_rejection() {
        let (tx, rx) = mpsc::sync_channel(32);
        let sender = DispatchSender {
            tx,
            in_flight: Arc::new(AtomicU64::new(0)),
            max_queue_depth: 32,
        };
        let barrier = Arc::new(std::sync::Barrier::new(32));
        std::thread::scope(|scope| {
            let mut workers = Vec::new();
            for id in 0..32 {
                let sender = sender.clone();
                let barrier = Arc::clone(&barrier);
                workers.push(scope.spawn(move || {
                    barrier.wait();
                    sender.enqueue(id, Vec::new())
                }));
            }
            for worker in workers {
                assert_eq!(worker.join().unwrap(), Ok(()));
            }
        });
        assert_eq!(
            sender.enqueue(33, Vec::new()),
            Err(Status::ResourceExhausted)
        );
        assert_eq!(rx.try_iter().count(), 32);
    }

    #[test]
    fn disconnected_and_full_channels_have_distinct_status_and_rollback() {
        let (tx, rx) = mpsc::sync_channel(1);
        let sender = DispatchSender {
            tx,
            in_flight: Arc::new(AtomicU64::new(0)),
            max_queue_depth: 2,
        };
        sender.enqueue(1, Vec::new()).unwrap();
        assert_eq!(
            sender.enqueue(2, Vec::new()),
            Err(Status::ResourceExhausted)
        );
        assert_eq!(sender.in_flight.load(Ordering::Acquire), 1);
        drop(rx);
        assert_eq!(sender.enqueue(3, Vec::new()), Err(Status::InvalidState));
        assert_eq!(sender.in_flight.load(Ordering::Acquire), 1);
    }

    struct NeverDispatch;
    impl Browser for NeverDispatch {
        fn new(_: crate::BrowserContext) -> crate::ApplicationResult<Self> {
            Ok(Self)
        }
        fn dispatch(&mut self, _: Command<'_>) -> crate::CommandResult {
            panic!("cancelled or expired work must not reach the application")
        }
    }

    unsafe extern "C" fn collect(
        data: *mut std::ffi::c_void,
        _: u64,
        _: RuntimeEventKind,
        bytes: ByteSlice,
    ) -> Status {
        // SAFETY: the test keeps the collection and payload alive through run_worker.
        let replies = unsafe { &*data.cast::<Mutex<Vec<Vec<u8>>>>() };
        let bytes = unsafe { std::slice::from_raw_parts(bytes.data, bytes.len) };
        replies.lock().unwrap().push(bytes.to_vec());
        Status::Ok
    }

    unsafe extern "C" fn reject_task(
        _user_data: *mut std::ffi::c_void,
        _priority: tuffite_abi::TaskPriority,
        _may_block: u8,
        _task_data: *mut std::ffi::c_void,
        _run: Option<tuffite_abi::TaskRunFn>,
        _destroy: Option<tuffite_abi::TaskDestroyFn>,
    ) -> Status {
        Status::InvalidState
    }

    fn rejected_work(stopping: bool, deadline: Duration, expected: &[u8]) {
        let (tx, rx) = mpsc::sync_channel(1);
        tx.send(DispatchTask {
            request_id: 42,
            event: Vec::new(),
            enqueued_at: Instant::now(),
        })
        .unwrap();
        drop(tx);
        let replies = Mutex::new(Vec::<Vec<u8>>::new());
        let callbacks = NativeHost(tuffite_abi::Host {
            header: tuffite_abi::Header::for_type::<tuffite_abi::Host>(),
            user_data: (&raw const replies).cast_mut().cast(),
            post_event: Some(collect),
            post_task: Some(reject_task),
            query_extension: None,
        });
        let application: Box<dyn Browser> = Box::new(NeverDispatch);
        let in_flight = Arc::new(AtomicU64::new(1));
        run_worker(
            &Arc::new(AtomicU64::new(1)),
            rx,
            application,
            callbacks,
            &in_flight,
            deadline,
            &AtomicBool::new(stopping),
        );
        let replies = replies.into_inner().unwrap();
        assert_eq!(replies.len(), 1);
        assert_eq!(protocol::response_request_id(&replies[0]), Some(42));
        assert_eq!(&replies[0][20..], expected);
        assert_eq!(in_flight.load(Ordering::Acquire), 0);
    }

    #[test]
    fn shutdown_cancels_queued_work_without_application_side_effects() {
        rejected_work(
            true,
            Duration::from_secs(30),
            SCHEDULER_CANCELLED_MSG.as_bytes(),
        );
    }

    #[test]
    fn queue_deadline_preserves_request_identity_and_releases_capacity() {
        rejected_work(false, Duration::ZERO, SCHEDULER_TIMEOUT_MSG.as_bytes());
    }
}
